import { test, expect } from './fixtures'

test('tags persist from Name through Publish and can change on a live quiz', async ({ page, seedQuiz, db }) => {
  const { id } = await seedQuiz()
  await page.goto(`/create/${id}/name`)
  const nameTags = page.getByRole('textbox', { name: 'Tags', exact: true })
  await nameTags.fill('Space Crew')
  await nameTags.press('Enter')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeDisabled()
  await page.goto(`/create/${id}/preview?tab=publish`)
  await expect(page.getByRole('button', { name: 'Remove tag space crew' })).toBeVisible()
  const publishTags = page.getByRole('textbox', { name: 'Tags', exact: true })
  await publishTags.fill('Orbit')
  await publishTags.press('Enter')
  await page.getByRole('button', { name: 'Publish quiz', exact: true }).click()
  await page.getByRole('button', { name: 'Close celebration' }).click()
  await page.getByRole('button', { name: 'Remove tag space crew' }).click()
  await page.getByRole('button', { name: 'Save tags', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save tags', exact: true })).toHaveCount(0)
  const quiz = await db.persona.findUniqueOrThrow({ where: { id } })
  expect(quiz.tags).toEqual(['orbit'])
  expect(quiz.status).toBe('PUBLISHED')
})
