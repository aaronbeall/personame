test('Publish tab reflects readiness, live and closed states and respects reduced motion', async ({ page, seedQuiz, db }) => {
  const { id } = await seedQuiz()
  const publishTab = page.getByRole('tab', { name: 'Publish', exact: true })
  await page.goto(`/create/${id}/preview`)
  await expect(publishTab).toHaveClass(/publish-tab-ready/)
  await expect(publishTab).toHaveAccessibleDescription('Ready to publish')
  await expect(publishTab).toHaveCSS('animation-name', 'publish-ready-pulse')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(publishTab).toHaveCSS('animation-name', 'none')

  await db.persona.update({ where: { id }, data: { status: 'PUBLISHED' } })
  await page.reload()
  await expect(publishTab).toHaveClass(/publish-tab-live/)
  await expect(publishTab).toHaveAccessibleDescription('Live · accepting responses')
  await db.persona.update({ where: { id }, data: { status: 'CLOSED' } })
  await page.reload()
  await expect(publishTab).toHaveClass(/publish-tab-closed/)
  await expect(publishTab).toHaveAccessibleDescription('Closed · not accepting responses')
  await expect(publishTab).toHaveCSS('animation-name', 'none')

  await db.persona.update({ where: { id }, data: { status: 'DRAFT', title: '' } })
  await page.reload()
  await expect(publishTab).toHaveClass(/publish-tab-incomplete/)
  await expect(publishTab).toHaveCSS('animation-name', 'none')
})

test('Workspace tabs use the URL across deep links, history, reload and publishing', async ({ page, seedQuiz }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const { id } = await seedQuiz()
  const base = `/create/${id}/preview`
  const keyWarnings: string[] = []
  page.on('console', message => { if (/same key|unique.*key/i.test(message.text())) keyWarnings.push(message.text()) })
  let publishCalls = 0
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith(`/api/personames/${id}/publish`)) publishCalls++ })
  await page.goto(`${base}?tab=analyze&keep=yes#workspace`)
  await expect(page.getByRole('tab', { name: 'Analyze', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('heading', { name: 'Your archetype atlas', exact: true })).toBeVisible()
  await expect(page.locator('.review-todos')).toHaveCount(0)
  await page.getByRole('tab', { name: 'Publish', exact: true }).click()
  await expect.poll(() => new URL(page.url()).searchParams.get('tab')).toBe('publish')
  expect(new URL(page.url()).searchParams.get('keep')).toBe('yes')
  expect(new URL(page.url()).hash).toBe('#workspace')
  await expect(page.getByRole('button', { name: 'Publish quiz', exact: true })).toBeEnabled()
  await expect(page.getByRole('heading', { name: 'Try it before you publish', exact: true })).toBeVisible()
  await expect(page.locator('.publish-preview-invite').getByRole('button', { name: 'Try the quiz', exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Discoverability' })).toBeDisabled()
  await expect(page.getByRole('combobox', { name: 'Publish timing' })).toBeDisabled()
  expect(publishCalls).toBe(0)
  await page.reload()
  await expect(page.getByRole('tab', { name: 'Publish', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.goBack()
  await expect(page.getByRole('tab', { name: 'Analyze', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.goForward()
  await expect(page.getByRole('tab', { name: 'Publish', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: 'Publish', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: 'Review', exact: true })).toBeFocused()
  await expect.poll(() => new URL(page.url()).searchParams.get('tab')).toBe('review')
  await expect(page.locator('.review-todos')).toBeVisible()
  await expect(page.getByRole('region', { name: 'Quiz summary', exact: true }).getByRole('button', { name: 'Try the quiz', exact: true })).toBeVisible()
  await expect(page.getByText('A final look at the world you’ve built.', { exact: true })).toHaveCount(0)
  await expect(page.locator('.archetype-space')).toHaveCount(0)
  await page.getByRole('link', { name: 'Continue to Publish', exact: true }).click()
  await expect.poll(() => new URL(page.url()).searchParams.get('tab')).toBe('publish')
  expect(new URL(page.url()).searchParams.get('keep')).toBe('yes')
  expect(publishCalls).toBe(0)
  await page.getByRole('button', { name: 'Publish quiz', exact: true }).click()
  await page.getByRole('button', { name: 'Close celebration' }).click()
  await expect(page.getByRole('button', { name: 'Close quiz', exact: true })).toBeEnabled()
  await expect(page.getByRole('link', { name: 'Open quiz', exact: true })).toBeVisible()
  expect(publishCalls).toBe(1)
  await expect(page.getByRole('tab', { name: 'Publish', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('tab', { name: 'Review', exact: true }).click()
  await expect(page.locator('.review-todos')).toHaveCount(0)
  await page.getByRole('link', { name: 'Manage publishing', exact: false }).click()
  await page.getByRole('button', { name: 'Close quiz', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Reopen quiz', exact: true })).toBeEnabled()
  await expect(page.getByRole('tab', { name: 'Publish', exact: true })).toHaveClass(/publish-tab-closed/)
  await page.locator('.publish-workspace').screenshot({ path: test.info().outputPath('publish-workspace.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.locator('body').evaluate(el => el.scrollWidth)).toBeLessThanOrEqual(390)
  await page.goto(`${base}?tab=unknown&keep=yes`)
  await expect(page.getByRole('tab', { name: 'Review', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('.review-todos')).toHaveCount(0)
  await page.goto(`${base}?tab=analyze`)
  await page.goto(`/create/${id}/name`)
  await page.goBack()
  await expect(page.getByRole('tab', { name: 'Analyze', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('region', { name: 'Your archetype atlas', exact: true })).toHaveCount(1)
  await expect(page.getByRole('region', { name: 'Targets & importance', exact: true })).toHaveCount(1)
  await expect(page.getByRole('region', { name: 'Your question space', exact: true })).toHaveCount(1)
  expect(keyWarnings).toEqual([])
})


test('Publishing can be closed and reopened without losing public results', async ({ page, seedQuiz, db }) => {
  const { id, slug } = await seedQuiz()
  await page.goto(`/create/${id}/preview?tab=publish`)
  await expect(page.locator('.publish-workspace > .publish-body .quiz-cover-mark')).toHaveCount(1)
  await expect(page.locator('.publish-workspace .publish-settings')).toBeVisible()
  const publish = page.getByRole('button', { name: 'Publish quiz', exact: true })
  await publish.hover()
  await expect(page.locator('.art-confetti')).toBeVisible()
  await page.locator('.publish-workspace').screenshot({ path: test.info().outputPath('publish-ready.png') })
  await publish.click()
  await page.getByRole('button', { name: 'Close celebration' }).click()
  await expect(page.getByRole('button', { name: 'Close quiz', exact: true })).toBeEnabled()
  const quiz = await (await page.request.get(`/api/quiz/${slug}`)).json()
  const responses = Object.fromEntries(quiz.pages.flatMap((p: { questions: { id: string; type: string; answers: { id: string }[] }[] }) => p.questions.map(q => [q.id, q.type === 'SLIDER' ? { value: 50 } : { answerId: q.answers[q.type === 'SCALE' ? 2 : 0].id }])))
  const submitted = await page.request.post(`/api/quiz/${slug}/submit`, { data: { revision: quiz.revision, submissionKey: crypto.randomUUID(), responses } })
  expect(submitted.ok(), await submitted.text()).toBeTruthy()
  const result = await submitted.json()
  const publishedAt = (await db.persona.findUniqueOrThrow({ where: { id } })).publishedAt
  await page.getByRole('button', { name: 'Close quiz', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Reopen quiz', exact: true })).toBeEnabled()
  const closed = await db.persona.findUniqueOrThrow({ where: { id } })
  expect(closed.status).toBe('CLOSED')
  expect(closed.visibility).toBe('PUBLIC')
  expect((await page.request.get(`/api/quiz/${slug}`)).status()).toBe(404)
  expect((await page.request.post(`/api/quiz/${slug}/submit`, { data: { revision: quiz.revision, submissionKey: crypto.randomUUID(), responses } })).status()).toBe(404)
  expect((await page.request.get(`/api/quiz/${slug}/results/${result.id}`)).ok()).toBeTruthy()
  await page.getByRole('button', { name: 'Reopen quiz', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Close quiz', exact: true })).toBeEnabled()
  const reopened = await db.persona.findUniqueOrThrow({ where: { id } })
  expect(reopened.status).toBe('PUBLISHED')
  expect(reopened.publishedAt).toEqual(publishedAt)
  expect((await page.request.get(`/api/quiz/${slug}`)).ok()).toBeTruthy()
  expect((await page.request.get(`/api/quiz/${slug}/results/${result.id}`)).ok()).toBeTruthy()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.locator('body').evaluate(el => el.scrollWidth)).toBeLessThanOrEqual(390)
  await page.locator('.publish-workspace').screenshot({ path: test.info().outputPath('publish-mobile.png') })
})
