test('result comparisons use only other completions of the same model and protect small cohorts', async ({page,seedQuiz,db}) => {
  const {id,slug} = await seedQuiz()
  await page.request.post(`/api/personames/${id}/publish`)
  const quiz = await (await page.request.get(`/api/quiz/${slug}`)).json()
  const responses = Object.fromEntries(quiz.pages.flatMap((p:{questions:{id:string;type:string;answers:{id:string}[]}[]})=>p.questions.map(q=>[q.id,q.type==='SLIDER'?{value:50}:{answerId:q.answers[q.type==='SCALE'?2:0].id}])))
  const submit = async () => { const response = await page.request.post(`/api/quiz/${slug}/submit`,{data:{responses,revision:quiz.revision,submissionKey:crypto.randomUUID()}}); expect(response.ok(),await response.text()).toBeTruthy(); return response.json() }
  const first = await submit()
  const url = `/api/quiz/${slug}/results/${first.id}`
  expect((await (await page.request.get(url)).json()).comparison.status).toBe('waiting')
  for(let i=0;i<9;i++) await submit()
  expect((await (await page.request.get(url)).json()).comparison.status).toBe('waiting')
  await submit()
  const payload = await (await page.request.get(url)).json()
  expect(payload.comparison.status).toBe('ready')
  expect(payload.comparison.completions).toBe(10)
  expect(payload.comparison.archetypeShare).toBe(1)
  expect(payload.comparison.dimensions.length).toBeGreaterThan(0)
  expect(Object.keys(payload).sort()).toEqual(['comparison','completedAt','snapshot'])
  for(const score of payload.snapshot.scores) { const other = payload.comparison.dimensions.find((d:{dimensionId:string})=>d.dimensionId===score.dimensionId); if(other) expect(other.average).toBeCloseTo(score.score) }
  await page.goto(`/quiz/${slug}/results/${first.id}`)
  await expect(page.getByText('100% of other completions shared your archetype.',{exact:false})).toBeVisible()
  await page.locator('.result-comparison').screenshot({path:test.info().outputPath('result-comparison.png')})
  await db.quizResult.updateMany({where:{personaId:id,id:{not:first.id}},data:{modelKey:'another-model'}})
  expect((await (await page.request.get(url)).json()).comparison.status).toBe('waiting')
})

test('publishing celebrates once, exposes share links, and respects reduced motion',async({page,seedQuiz})=>{
  await page.emulateMedia({reducedMotion:'reduce'})
  const {id,slug}=await seedQuiz()
  await page.goto(`/create/${id}/preview?tab=publish`)
  await page.getByRole('button',{name:'Publish quiz',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Your quiz is out in the world!'})
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('textbox',{name:'Published quiz link'})).toHaveValue(new RegExp(`/quiz/${slug}$`))
  await expect(dialog.getByRole('link',{name:'WhatsApp'})).toHaveAttribute('href',/wa.me/)
  await expect(page.locator('.art-confetti-screen')).toHaveCount(0)
  await dialog.screenshot({path:test.info().outputPath('publish-celebration.png')})
  await page.getByRole('button',{name:'Close celebration'}).click()
  await page.reload()
  await expect(page.getByRole('button',{name:'Close quiz',exact:true})).toBeVisible()
  await expect(dialog).toHaveCount(0)
})

