import { test, expect } from './fixtures'
import { randomUUID } from 'node:crypto'

test('bounded collections, no-op saves, concurrent submissions and cache invalidation', async ({ page, seedQuiz, db, account }) => {
  const { id, slug } = await seedQuiz()
  await seedQuiz()
  const path = `/api/personames/${id}`
  await test.step('Pagination filters on the server but keeps collection totals', async () => {
    const response = await page.request.get('/api/me/quizzes?limit=1&status=DRAFT')
    const first = await response.json()
    expect(first.items).toHaveLength(1)
    expect(first.counts.DRAFT).toBe(2)
    expect(first.hasMore).toBe(true)
    const second = await (await page.request.get('/api/me/quizzes?limit=1&status=DRAFT&page=2')).json()
    expect(second.items[0].id).not.toBe(first.items[0].id)
    expect((await page.request.get('/api/me/quizzes?limit=100000')).status()).toBe(400)
    expect(first.items[0]).not.toHaveProperty('pages')
    expect((await (await page.request.get('/api/me/quizzes?search=%25')).json()).total).toBe(0)
  })
  await test.step('An unchanged save preserves relationship IDs', async () => {
    const pages = await (await page.request.get(`${path}/questions`)).json()
    const before = await db.answerWeight.findMany({ where: { answer: { question: { page: { personaId: id } } } }, orderBy: { id: 'asc' } })
    expect((await page.request.post(`${path}/questions`, { data: { pages } })).ok()).toBeTruthy()
    const after = await db.answerWeight.findMany({ where: { answer: { question: { page: { personaId: id } } } }, orderBy: { id: 'asc' } })
    expect(after).toEqual(before)
  })
  await test.step('Concurrent completions commit once each, including duplicate delivery', async () => {
    expect((await page.request.post(`${path}/publish`)).ok()).toBeTruthy()
    const quiz = await (await page.request.get(path)).json()
    const responses: Record<string, { answerId?: string; value?: number }> = {}
    for (const p of quiz.pages.filter((p: { hidden: boolean; style: string }) => !p.hidden && p.style !== 'cover' && p.style !== 'results'))
      for (const q of p.questions) responses[q.id] = q.type === 'MULTIPLE_CHOICE' ? { answerId: q.answers[0].id } : q.type === 'SCALE' ? { answerId: q.answers[2].id } : { value: 50 }
    const keys = Array.from({ length: 5 }, () => randomUUID())
    const results = await Promise.all([...keys, keys[0]].map(submissionKey => page.request.post(`/api/quiz/${slug}/submit`, { data: { revision: quiz.updatedAt, submissionKey, responses } })))
    for (const result of results) expect(result.status(), await result.text()).toBe(200)
    expect((await results[0].json()).id).toBe((await results[5].json()).id)
    expect((await db.persona.findUniqueOrThrow({ where: { id } })).completions).toBe(5)
    const discoveries = await (await page.request.get('/api/me/discoveries?limit=1')).json()
    expect(discoveries.items).toHaveLength(1)
    expect(discoveries.collectionTotal).toBe(1)
    expect(discoveries.items[0]).not.toHaveProperty('snapshot')
    const counts = await (await page.request.get('/api/me/counts')).json()
    expect(counts.selvesCount).toBe(1)
    expect(await db.quizResult.count({ where: { userId: account.id, personaId: id } })).toBe(5)
  })
  await test.step('Warm public data revokes immediately on close and edit', async () => {
    const publicData = await (await page.request.get(`/api/quiz/${slug}`)).json()
    expect(publicData).not.toHaveProperty('archetypes')
    for (const p of publicData.pages) for (const q of p.questions) for (const a of q.answers) expect(a).not.toHaveProperty('weights')
    expect((await (await page.request.get('/api/personames')).json()).some((q: { id: string }) => q.id === id)).toBe(true)
    expect((await page.request.patch(path, { data: { status: 'CLOSED' } })).ok()).toBeTruthy()
    expect((await page.request.get(`/api/quiz/${slug}`)).status()).toBe(404)
    expect((await (await page.request.get('/api/personames')).json()).some((q: { id: string }) => q.id === id)).toBe(false)
    expect((await page.request.post(`${path}/publish`)).ok()).toBeTruthy()
    expect((await page.request.get(`/api/quiz/${slug}`)).ok()).toBeTruthy()
    const dimensions = await (await page.request.get(`${path}/dimensions`)).json()
    expect((await page.request.post(`${path}/dimensions`, { data: { dimensions } })).ok()).toBeTruthy()
    expect((await page.request.get(`/api/quiz/${slug}`)).status()).toBe(404)
    expect((await (await page.request.get('/api/personames')).json()).some((q: { id: string }) => q.id === id)).toBe(false)
  })
  await test.step('Collection controls page and search beyond the first page', async () => {
    const fixtures = Array.from({ length: 25 }, (_, i) => ({
      id: randomUUID(), title: `Pagination draft ${i}`, slug: `pagination-${randomUUID()}`, creatorId: account.id,
    }))
    await db.persona.createMany({ data: fixtures })
    await db.quizResult.createMany({ data: fixtures.map(quiz => ({
      personaId: quiz.id, userId: account.id,
      snapshot: { archetype: { name: `Self from ${quiz.title}`, description: 'A pagination fixture', emoji: '✨', color: '#4257be' } },
    })) })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/quizzes')
    await expect(page.getByRole('article')).toHaveCount(24)
    const bottom = page.getByRole('navigation', { name: 'quizzes pagination' })
    await expect(page.getByRole('navigation', { name: /quizzes pagination/ })).toHaveCount(1)
    await expect(bottom).toBeVisible()
    await expect(bottom).toContainText('1–24 of 27 quizzes')
    await page.getByRole('navigation', { name: 'quizzes pagination' }).getByRole('button', { name: 'Next page', exact: true }).click()
    await expect(page.getByRole('article')).toHaveCount(3)
    await expect(bottom.getByRole('button', { name: 'Page 2', exact: true })).toHaveAttribute('aria-current', 'page')
    await bottom.getByRole('button', { name: 'Previous page', exact: true }).click()
    await expect(page.getByRole('article')).toHaveCount(24)
    await expect(page.locator('#quiz-collection')).toBeInViewport()
    await bottom.getByRole('button', { name: 'Page 2', exact: true }).click()
    await expect(page.getByRole('article')).toHaveCount(3)
    await page.screenshot({ path: test.info().outputPath('pagination-desktop.png') })
    await page.setViewportSize({ width: 375, height: 844 })
    await expect.poll(() => page.locator('body').evaluate(el => el.scrollWidth)).toBeLessThanOrEqual(375)
    await page.screenshot({ path: test.info().outputPath('pagination-mobile.png') })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.getByRole('searchbox', { name: 'Search quizzes', exact: true }).fill('Pagination draft 24')
    await expect(page.getByRole('article')).toHaveCount(1)
    await expect(page.getByRole('tab', { name: /^Drafts/ })).toContainText('27')
    await page.goto('/selves')
    await expect(page.getByRole('article')).toHaveCount(24)
    await page.getByRole('navigation', { name: 'selves pagination' }).getByRole('button', { name: 'Next page', exact: true }).click()
    await expect(page.getByRole('article')).toHaveCount(2)
    await page.getByRole('searchbox', { name: 'Search your selves', exact: true }).fill('Pagination draft 24')
    await expect(page.getByRole('article')).toHaveCount(1)
    await expect(page.getByRole('tab', { name: /^Discovered/ })).toContainText('26')
  })
})
